// Offline verification of captured LIVE evidence. Never fetches or loads a credential.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const read = async path => JSON.parse(await readFile(path,'utf8'));
const smoke=await read('evidence/gate2a-smoke-redacted.json');
const upstream=await read('evidence/gate2a-upstream.json');
const live=await read('evidence/gate2a-live.json');
const report=await read('evidence/gate2a-report-redacted.json');
const responses=upstream.records.filter(r=>r.httpStatus);
const insights=responses.filter(r=>r.endpoint==='/v2/insights');
assert.equal(smoke.response.status,200);
assert.equal(responses.length,5);
assert.ok(responses.every(r=>r.httpStatus===200));
assert.equal(responses.filter(r=>r.endpoint==='/search').length,4);
assert.equal(insights.length,1);
assert.equal(live.status,'SUCCESS');
assert.equal(live.identities.length,4);
assert.ok(live.identities.every(r=>r.exactMatches===1&&r.upstreamHttpStatus===200));
const insight=insights[0];
const candidates=live.identities.filter(i=>i.role==='recommendation').map(i=>i.idHash);
assert.deepEqual(insight.sentSignalHashes,live.identities.filter(i=>i.role==='interest').map(i=>i.idHash));
assert.deepEqual(insight.sentCandidateHashes,candidates);
assert.equal(insight.allReturnedIdsBelongToRequestedCandidates,true);
assert.deepEqual(new Set(insight.entities.map(e=>e.idHash)),new Set(candidates));
assert.ok(insight.entities.every(e=>e.subtypeMovie&&e.affinityFieldPresent&&Number.isFinite(e.returnedAffinity)));
assert.ok(insight.entities.every((e,i,a)=>i===0||a[i-1].returnedAffinity>=e.returnedAffinity));
assert.deepEqual(live.audit.coverage,{returned:3,total:3});
assert.equal(report.liveResponseReceived,true);
assert.equal(report.evaluation.provenance.host,'https://hackathon.api.qloo.com');
assert.equal(report.evaluation.provenance.parameters['filter.type'],'urn:entity:movie');
assert.equal(report.evaluation.provenance.parameters.take,'3');
assert.ok(!JSON.stringify(report).includes('proof'));
for(const row of live.audit.rows) assert.equal(row.qlooRank,insight.entities.findIndex(e=>e.idHash===row.idHash)+1);
const verification={ timestamp:new Date().toISOString(),mode:'OFFLINE_VERIFICATION_OF_LIVE_CAPTURE',status:'PASS',confirmedHTTPResponses:1+responses.length,searchHTTPResponses:5,insightsHTTPResponses:1,transportFailuresWithoutHTTP:1+upstream.records.filter(r=>!r.httpStatus).length,verifiedIdentities:4,coverage:live.audit.coverage,exactCandidateSet:true,movieDomain:true,returnedOrderMatchesDescendingObservedAffinity:true,signalSentMatchesConfirmedInterest:true,signalParameterEchoPresent:Object.values(insight.requestParametersEchoed).some(Boolean),limitations:['The response does not echo the requested signal; accepted request parameters and same-candidate results do not independently prove provider internals or causality.','One Insights response was captured. No repeat or alternate-signal control was requested, to respect the six-response API budget.','Numeric affinity was observed at query.affinity but the current product remains rank-only and retains affinity=null.','Offline verification makes zero additional Qloo requests.'] };
await writeFile('evidence/gate2a-verification.json',JSON.stringify(verification,null,2)+'\n');
console.log(JSON.stringify(verification));
